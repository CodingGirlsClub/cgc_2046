/** 有序内容块：段落或（可选小标题的）条目组，保序渲染 */
export type PrivacyBlock =
  | { kind: 'p'; text: string; title?: string }
  | { kind: 'items'; title?: string; items: string[] }

export interface PrivacySection {
  title: string
  blocks: PrivacyBlock[]
}

