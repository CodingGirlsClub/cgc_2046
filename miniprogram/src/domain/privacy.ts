/** 平台名枚举处 spec（两份变体文件的唯一差异面） */
export interface PrivacySpec {
  /** INTRO 的适用范围句（「含 … 端」） */
  introScope: string
  /** 1.1 手机号条目（平台快捷登录枚举） */
  phoneItem: string
  /** 1.2 平台身份标识条目 */
  platformIdentityItem: string
  /** 第 2 节「目的」里的支付条目 */
  paymentPurposeItem: string
  /** 第 5 节第三方服务清单（全量） */
  thirdPartyItems: string[]
  /** 附录「委托处理与对外提供」首条（与第 5 节清单同口径） */
  delegationLead: string
}

export function privacyIntro(spec: PrivacySpec): string {
  return `${spec.introScope}本政策说明我们收集哪些个人信息、如何使用与保护、您拥有哪些权利。使用本平台即表示您已阅读并同意本政策。`
}

